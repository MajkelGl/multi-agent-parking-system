def run_evaluation():
    k_values = [1, 3, 5]
    llm_as_a_judge, _ = load_models_and_milvus()

    judge_template = """
    You are an impartial AI judge evaluating a RAG (Retrieval-Augmented Generation) system.
    You will be provided with a Question, the Ground Truth answer, the Retrieved Context from the vector database, and the Final Answer generated by the RAG system.

    Evaluate the system on two metrics (scale 1 to 5, where 5 is the best):
    1. Context Relevance: Does the 'Retrieved Context' contain the necessary information to answer the question?
    2. Answer Correctness: Is the 'Final Answer' factually correct according to the 'Ground Truth' and does it directly answer the question?

    Question: {question}
    Ground Truth: {ground_truth}
    Retrieved Context: {context}
    Final Answer: {retrieved_answer}

    RETURN ONLY A VALID JSON OBJECT. NO MARKDOWN, NO EXPLANATION TEXT.
    Format:
    {{
        "context_relevance": <int>,
        "answer_correctness": <int>,
        "reasoning": "<short string explaining the scores>"
    }}
    """
    
    judge_prompt = PromptTemplate.from_template(judge_template)
    evaluation_chain = judge_prompt | llm_as_a_judge | StrOutputParser()

    print("Starting RAG evaluation (LLM-as-a-Judge)...")
    
    with open("evaluation_report.txt", "w", encoding="utf-8") as f:
        f.write(" RAG SYSTEM EVALUATION REPORT \n\n")

        for k in k_values:
            print(f"\nEvaluating Top-K = {k}...")
            f.write(f" EXPERIMENT WITH TOP-K = {k} \n")
            
            total_context_score = 0
            total_answer_score = 0
            total_questions = len(EVALUATION_DATASET)
            
            results_log = []

            for idx, data in enumerate(EVALUATION_DATASET):
                question = data["question"]
                ground_truth = data["ground_truth"]

                retrieved_answer, context = run_milvus_query(question, k=k, return_context=True)
                
                raw_eval = evaluation_chain.invoke({
                    "question": question,
                    "ground_truth": ground_truth,
                    "context": context,
                    "retrieved_answer": retrieved_answer
                })
                
                clean_json = raw_eval.replace("```json", "").replace("```", "").strip()
                
                try:
                    eval_data = json.loads(clean_json)
                    c_score = eval_data.get("context_relevance", 0)
                    a_score = eval_data.get("answer_correctness", 0)
                    reason = eval_data.get("reasoning", "No reasoning provided.")
                except Exception as e:
                    print(f"Failed to parse JSON for question {idx+1}. Fallback to 0. Raw output: {clean_json}")
                    c_score = 0
                    a_score = 0
                    reason = "Failed to parse JSON response."
                
                total_context_score += c_score
                total_answer_score += a_score
                
                results_log.append(
                    f"Q{idx+1}: {question}\n"
                    f"Context Score: {c_score}/5 | Answer Score: {a_score}/5\n"
                    f"Reasoning: {reason}\n"
                    f"Answer Generated: {retrieved_answer}\n"
                )
                
            avg_context = total_context_score / total_questions
            avg_answer = total_answer_score / total_questions
            
            f.write(f"Average Context Relevance: {avg_context:.2f}/5.0\n")
            f.write(f"Average Answer Correctness: {avg_answer:.2f}/5.0\n\n")
            f.write("Detailed Breakdown:\n")
            
            for log in results_log:
                f.write(log)
                
            f.write("\n\n")
            
    print("\nEvaluation completed successfully. Check 'evaluation_report.txt'.")

if __name__ == "__main__":
    run_evaluation()